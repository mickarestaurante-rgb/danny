    """Carga el PUC completo en la base de datos"""
    inserted = 0
    for row in PUC:
        try:
            db.execute("""INSERT OR IGNORE INTO plan_cuentas
                          (codigo, nombre, nivel, clase, tipo, naturaleza,
                           codigo_padre, permite_movimiento, exige_tercero)
                          VALUES (?,?,?,?,?,?,?,?,?)""", row)
            inserted += 1
        except Exception:
            pass
    db.commit()
    return inserted


